const fs = require('fs/promises');
const path = require('path');

async function generateThemes() {
  const revealPackageJsonPath = require.resolve('reveal.js/package.json');
  const revealPackageDir = path.dirname(revealPackageJsonPath);
  const themeDir = path.join(revealPackageDir, 'dist', 'theme');

  const destDir = path.join(process.cwd(), 'public', 'themes');
  await fs.mkdir(destDir, { recursive: true });

  const libDir = path.join(process.cwd(), 'src', 'lib');
  await fs.mkdir(libDir, { recursive: true });

  const files = await fs.readdir(themeDir);
  const cssFiles = files
    .filter((file) => file.endsWith('.css'))
    .filter((file) => !file.includes('white_contrast_compact_verbatim_headers'));

  await Promise.all(
    cssFiles.map((file) =>
      fs.copyFile(path.join(themeDir, file), path.join(destDir, file))
    )
  );

  // Copy bundled fonts used by some themes
  const fontsDir = path.join(themeDir, 'fonts');
  const fontsDestDir = path.join(destDir, 'fonts');
  try {
    await fs.cp(fontsDir, fontsDestDir, { recursive: true });
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
  }

  // Copy slidesmd's own themes (src/themes/*.css); tolerate the directory
  // being absent (npm's prepare script runs before old checkouts have it).
  const customThemeDir = path.join(process.cwd(), 'src', 'themes');
  let customFiles = [];
  try {
    customFiles = (await fs.readdir(customThemeDir))
      .filter((file) => file.endsWith('.css'))
      .sort();
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
  }
  await Promise.all(
    customFiles.map((file) =>
      fs.copyFile(path.join(customThemeDir, file), path.join(destDir, file))
    )
  );

  // Custom themes first so they lead the selector.
  const allThemes = [...customFiles, ...cssFiles.filter((f) => !customFiles.includes(f))];
  const content = `// This file is generated by scripts/generate-themes.js\nexport const themes = ${JSON.stringify(allThemes, null, 2)};\n`;
  await fs.writeFile(path.join(process.cwd(), 'src', 'lib', 'themes.ts'), content);
  console.log('Generated themes:', allThemes);
}

module.exports = { generateThemes };

if (require.main === module) {
  generateThemes().catch((err) => {
    console.error('Failed to generate themes', err);
    process.exit(1);
  });
}
